    public updateChungChi(java.awt.Frame parent, boolean modal, chungChiETT data) {
        super(parent, modal);
        initComponents();
        this.chungChi = data;
        setLocationRelativeTo(parent);

        // 1. Khóa các ô không nên sửa khi cập nhật (như CCCD)
        txtCCCD.setText(data.getCccd());
        txtCCCD.setEditable(false); 
        txtDiemQuyDoi.setEditable(false);
        txtDiemCong.setEditable(false);

        // 2. Đổ dữ liệu cũ lên các thành phần điều khiển
        cboLoaiChungChi.setSelectedItem(data.getLoaiChungChi());
        txtDiemQuyDoi.setText(String.valueOf(data.getDiemQuyDoi()));
        txtDiemCong.setText(String.valueOf(data.getDiemCong()));

        // 3. Xử lý hiển thị Panel và phân rã điểm
        String loai = data.getLoaiChungChi();
        String diemGoc = data.getDiemChungChi();

        if (loai.equals("Tiếng Anh - TOEIC (4 kỹ năng)")) {
            pnlNormal.setVisible(false);
            pnlToeic4.setVisible(true);
            
            // Phân rã chuỗi "Nghe/Đọc/Nói/Viết" để điền vào 4 ô
            String[] scores = diemGoc.split("/");
            if (scores.length == 4) {
                txtNghe.setText(scores[0]);
                txtDoc.setText(scores[1]);
                txtNoi.setText(scores[2]);
                txtViet.setText(scores[3]);
            }
        } else {
            pnlNormal.setVisible(true);
            pnlToeic4.setVisible(false);
            txtDiemChungChi.setText(diemGoc);
        }
        
        this.pack(); // Co giãn giao diện cho vừa khít
    }
