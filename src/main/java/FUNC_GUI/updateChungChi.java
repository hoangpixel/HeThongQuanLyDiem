// Hàm 2: Tự động tính điểm (Cái này mình đã viết ở câu trước, Đạt dán vào đây)
private void tinhToanDiem() {
    String loai = cboLoaiChungChi.getSelectedItem().toString();
    double qd = 0; 
    double cg = 0; 
    String cccd = txtCCCD.getText().trim();

    try {
        if (loai.equals("Tiếng Anh - TOEIC (4 kỹ năng)")) {
            if(txtNghe.getText().isEmpty() || txtDoc.getText().isEmpty()) return;
            // Ép kiểu số cho 4 kỹ năng TOEIC
            int n = Integer.parseInt(txtNghe.getText().trim());
            int d = Integer.parseInt(txtDoc.getText().trim());
            int s = Integer.parseInt(txtNoi.getText().trim());
            int w = Integer.parseInt(txtViet.getText().trim());
            
            int levelNghe = (n >= 490) ? 10 : (n >= 400) ? 9 : (n >= 275) ? 8 : 0;
            int levelDoc  = (d >= 455) ? 10 : (d >= 385) ? 9 : (d >= 275) ? 8 : 0;
            int levelNoi  = (s >= 180) ? 10 : (s >= 160) ? 9 : (s >= 120) ? 8 : 0;
            int levelViet = (w >= 180) ? 10 : (w >= 150) ? 9 : (w >= 120) ? 8 : 0;
            qd = Math.min(Math.min(levelNghe, levelDoc), Math.min(levelNoi, levelViet));
        } 
        else {
            // LẤY TỪ Ô TEXTFIELD MỚI ĐỔI TÊN
            String input = txtDiemChungChi.getText().trim();
            if(input.isEmpty()) return;

            if (loai.equals("Tiếng Anh - IELTS")) {
                double v = Double.parseDouble(input);
                qd = (v >= 7.0) ? 10 : (v >= 5.5) ? 9 : (v >= 4.0) ? 8 : 0;
            } 
            else if (loai.equals("Tiếng Anh - TOEFL ITP")) {
                int v = Integer.parseInt(input);
                qd = (v >= 627) ? 10 : (v >= 500) ? 9 : (v >= 450) ? 8 : 0;
            }
            else if (loai.equals("Tiếng Anh - VSTEP")) {
                if (input.contains("5")) qd = 10;
                else if (input.contains("4")) qd = 9;
                else if (input.contains("3")) qd = 8;
            }
            // Thêm các case TOEFL iBT, PTE... tương tự
        }

        // Tính điểm quy đổi và cộng (Logic cũ)
        if (qd == 10) cg = 2.0;
        else if (qd == 9) cg = 1.5;
        else if (qd == 8) cg = 1.0;

        txtDiemQuyDoi.setText(String.valueOf(qd));
        
        // chungChiBUS bus = new chungChiBUS();
        if (bus.checkToHopCoMonAnh(txtCCCD.getText().trim())) {
                txtDiemCong.setText("0.0");
        } else {
            txtDiemCong.setText(String.valueOf(cg));
        }

    } catch (Exception e) {
        txtDiemQuyDoi.setText("0");
        txtDiemCong.setText("0");
    }
}

