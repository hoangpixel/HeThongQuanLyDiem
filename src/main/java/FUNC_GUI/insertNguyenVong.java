        ct.setNvMaNganh(maNganh);
        ct.setNvTt(thuTuNV);
        ct.setDiemThxt(diemTHXT);
        
        // 🚀 LƯU Ý LỚN: Vẫn lưu diemUTQDGoc (ví dụ 2.5) nguyên vẹn xuống DB để in giấy tờ!
