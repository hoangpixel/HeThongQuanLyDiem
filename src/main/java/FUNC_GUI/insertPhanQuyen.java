    // 2. Hàm set tick cho 1 hàng (Ngắn gọn code)
    private void setRowCheck(JCheckBox xem, JCheckBox them, JCheckBox sua, JCheckBox xoa, boolean vXem, boolean vThem, boolean vSua, boolean vXoa) {
        if(xem != null) xem.setSelected(vXem);
        if(them != null) them.setSelected(vThem);
        if(sua != null) sua.setSelected(vSua);
        if(xoa != null) xoa.setSelected(vXoa);
    }

    // 3. Hàm cốt lõi: Móc DB và Tick lên Form
    private void loadQuyenCuLenForm(int idTK) {
        clearAllCheckBoxes(); // Dọn rác trước khi load
        
        DAO.phanQuyenDAO dao = new DAO.phanQuyenDAO();
        java.util.List<Entity.phanQuyenETT> dsQuyen = dao.layDanhSachQuyen(idTK);
        
        if (dsQuyen == null) return;

        for (Entity.phanQuyenETT q : dsQuyen) {
            boolean xem = q.getQuyenXem() == 1;
            boolean them = q.getQuyenThem() == 1;
            boolean sua = q.getQuyenSua() == 1;
            boolean xoa = q.getQuyenXoa() == 1;

            switch (q.getTenBang()) {
                case "xt_nguyenvongxettuyen": setRowCheck(ckXemNV, ckThemNV, ckSuaNV, ckXoaNV, xem, them, sua, xoa); break;
                case "xt_bangquydoi": setRowCheck(ckXemQD, ckThemQD, ckSuaQD, ckXoaQD, xem, them, sua, xoa); break;
                case "xt_chungchi": setRowCheck(ckXemCC, ckThemCC, ckSuaCC, ckXoaCC, xem, them, sua, xoa); break;
                case "xt_giathuong": setRowCheck(ckXemGT, ckThemGT, ckSuaGT, ckXoaGT, xem, them, sua, xoa); break;
                case "xt_diemthixettuyen": setRowCheck(ckXemDT, ckThemDT, ckSuaDT, ckXoaDT, xem, them, sua, xoa); break;
                case "xt_diemcongxetuyen": setRowCheck(ckXemDC, ckThemDC, ckSuaDC, ckXoaDC, xem, them, sua, xoa); break;
                case "xt_nganh": setRowCheck(ckXemN, ckThemN, ckSuaN, ckXoaN, xem, them, sua, xoa); break;
                case "xt_nganh_tohop": setRowCheck(ckXemNTH, ckThemNTH, ckSuaNTH, ckXoaNTH, xem, them, sua, xoa); break;
                case "xt_tohop_monthi": setRowCheck(ckXemTHM, ckThemTHM, ckSuaTHM, ckXoaTHM, xem, them, sua, xoa); break;
                case "xt_thisinhxettuyen25": setRowCheck(ckXemTS, ckThemTS, ckSuaTS, ckXoaTS, xem, them, sua, xoa); break;
                case "xt_taikhoan": setRowCheck(ckXemTK, ckThemTK, ckSuaTK, ckXoaTK, xem, them, sua, xoa); break;
            }
        }
    }
