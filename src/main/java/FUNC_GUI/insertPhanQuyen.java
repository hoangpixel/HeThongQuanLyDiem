    private phanQuyenETT layQuyenTuRow(int idTaiKhoan, String tenBang, JCheckBox ckXem, JCheckBox ckThem, JCheckBox ckSua, JCheckBox ckXoa) 
    {
        phanQuyenETT pq = new Entity.phanQuyenETT();
        pq.setIdTaiKhoan(idTaiKhoan);
        pq.setTenBang(tenBang);
        pq.setQuyenXem(ckXem.isSelected() ? 1 : 0);
        pq.setQuyenThem(ckThem.isSelected() ? 1 : 0);
        pq.setQuyenSua(ckSua.isSelected() ? 1 : 0);
        pq.setQuyenXoa(ckXoa.isSelected() ? 1 : 0);
    return pq;
}
    private ArrayList<phanQuyenETT> danhSachThenPhanQuyen = new ArrayList<>();
    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        // TODO add your handling code here:
        
        if(txtIdTaiKhoan.getText().isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn tài khoản cần cấp quyền!");
            return;
        }
        
        ArrayList<phanQuyenETT> dsQuyenMoi = new ArrayList<>();
        dsQuyenMoi.add(layQuyenTuRow(idTaiKhoan, "xt_nguyenvongxettuyen", ckXemNV, ckThemNV, ckSuaNV, ckXoaNV));
        dsQuyenMoi.add(layQuyenTuRow(idTaiKhoan, "xt_bangquydoi", ckXemQD, ckThemQD, ckSuaQD, ckXoaQD));
        dsQuyenMoi.add(layQuyenTuRow(idTaiKhoan, "xt_chungchi", ckXemCC, ckThemCC, ckSuaCC, ckXoaCC));
        dsQuyenMoi.add(layQuyenTuRow(idTaiKhoan, "xt_giathuong", ckXemGT, ckThemGT, ckSuaGT, ckXoaGT));
        dsQuyenMoi.add(layQuyenTuRow(idTaiKhoan, "xt_diemthixettuyen", ckXemDT, ckThemDT, ckSuaDT, ckXoaDT));
        dsQuyenMoi.add(layQuyenTuRow(idTaiKhoan, "xt_diemcongxetuyen", ckXemDC, ckThemDC, ckSuaDC, ckXoaDC));
        dsQuyenMoi.add(layQuyenTuRow(idTaiKhoan, "xt_nganh", ckXemN, ckThemN, ckSuaN, ckXoaN));
        dsQuyenMoi.add(layQuyenTuRow(idTaiKhoan, "xt_nganh_tohop", ckXemNTH, ckThemNTH, ckSuaNTH, ckXoaNTH));
        dsQuyenMoi.add(layQuyenTuRow(idTaiKhoan, "xt_tohop_monthi", ckXemTHM, ckThemTHM, ckSuaTHM, ckXoaTHM));
        dsQuyenMoi.add(layQuyenTuRow(idTaiKhoan, "xt_thisinhxettuyen25", ckXemTS, ckThemTS, ckSuaTS, ckXoaTS));
        dsQuyenMoi.add(layQuyenTuRow(idTaiKhoan, "xt_taikhoan", ckXemTK, ckThemTK, ckSuaTK, ckXoaTK));
        
        phanQuyenBUS pqBus = new phanQuyenBUS();
    if (pqBus.luuPhanQuyen(idTaiKhoan, dsQuyenMoi)) {
        JOptionPane.showMessageDialog(this, "Cấp quyền thành công!");
        danhSachThenPhanQuyen = dsQuyenMoi;
        xacNhan = true;
        dispose();
    } else {
        JOptionPane.showMessageDialog(this, "Lỗi khi cấp quyền!");
    }
    }//GEN-LAST:event_btnThemActionPerformed

